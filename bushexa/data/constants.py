import re

_PAREN_RE = re.compile(r"\s*\([^)]*\)")


def clean_stop_name(name: str) -> str:
    """정류장명에서 괄호 주석((시내)/(UNIST)/(경유)/(기점)/(종점) 등)을 제거.

    STOP_IDS 명칭 정규화의 단일 구현 — composite_location·domain/board가 공용.
    """
    return _PAREN_RE.sub("", name or "").strip()


